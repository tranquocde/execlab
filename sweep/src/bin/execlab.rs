//! execlab — execution sweep runner.
//!
//!   cargo run --release --bin execlab                        every registered alpha
//!   cargo run --release --bin execlab -- mm_spread           one
//!   cargo run --release --bin execlab -- mm_spread momentum  a subset
//!   cargo run --release --bin execlab -- --list              what is registered
//!   cargo run --release --bin execlab -- --data-dir data mm_spread
//!   cargo run --release --bin execlab -- --data-dir data/5m --batch 32 mm_spread
//!   cargo run --release --bin execlab -- --data-dir data/5m/tcb mm_spread
//!   cargo run --release --bin execlab -- --force mm_spread   ignore completion markers
//!
//! Adding an alpha: drop a file in src/alphas/. build.rs finds it, hashes it,
//! registers it. Nothing here changes.

use execlab::{alphas, engine, status, Entry};

use std::{env, fs, path::Path, time::Instant};

// ---------------------------------------------------------------- registry

// ---------------------------------------------------------------- cli

struct Args {
    data_dir: Option<String>,
    out_dir: String,
    batch: usize,
    workers: Option<usize>,
    only: Vec<String>,
    force: bool,
    list: bool,
    status: bool,
}

fn parse_args() -> Args {
    let mut a = Args {
        data_dir: None,
        out_dir: "output".into(),
        batch: 16,
        workers: None,
        only: Vec::new(),
        force: false,
        list: false,
        status: false,
    };

    let mut it = env::args().skip(1);
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "--data-dir" => a.data_dir = Some(it.next().expect("--data-dir needs a value")),
            "--out" => a.out_dir = it.next().expect("--out needs a value"),
            "--batch" => a.batch = it.next().unwrap().parse().expect("--batch needs a number"),
            "--max-workers" => a.workers = it.next().and_then(|v| v.parse().ok()),
            "--force" => a.force = true,
            "--list" => a.list = true,
            "--status" => a.status = true,
            other => a.only.push(other.to_string()), // positional = alpha name
        }
    }
    a
}

// ---------------------------------------------------------------- main

fn main() {
    let args = parse_args();
    let registry = alphas::registry(); // generated by build.rs

    if args.list {
        for e in &registry {
            println!("{:<20} code={}", e.name, e.code_hash);
        }
        return;
    }

    // Fail loudly on a typo. Otherwise `-- mm_sread` prints nothing and looks
    // like a fast successful run.
    for want in &args.only {
        if !registry.iter().any(|e| e.name == *want) {
            eprintln!("unknown alpha: {want}");
            eprintln!(
                "available: {}",
                registry
                    .iter()
                    .map(|e| e.name)
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            std::process::exit(1);
        }
    }

    // Read-only; runs before the data dir is even touched, so `--status` works
    // without a valid --data-dir and is safe to run mid-sweep.
    if args.status {
        let out = Path::new(&args.out_dir);
        for e in registry
            .iter()
            .filter(|e| args.only.is_empty() || args.only.iter().any(|w| w == e.name))
        {
            status::report(out, e.name, e.code_hash, e.total_space);
        }
        println!();
        return;
    }

    if let Some(w) = args.workers {
        rayon::ThreadPoolBuilder::new()
            .num_threads(w)
            .build_global()
            .unwrap();
    }

    let data_dir = args.data_dir.as_deref().unwrap_or_else(|| {
        eprintln!("--data-dir is required for a sweep (for example: --data-dir data/5m/<market>)");
        std::process::exit(1);
    });

    let market_dirs = engine::market_dirs(data_dir).unwrap_or_else(|error| {
        eprintln!("{error}");
        std::process::exit(1);
    });
    let data_root = engine::data_root(&market_dirs).unwrap_or_else(|error| {
        eprintln!("{error}");
        std::process::exit(1);
    });
    let out = Path::new(&args.out_dir);
    fs::create_dir_all(out).unwrap();

    let selected: Vec<&Entry> = registry
        .iter()
        .filter(|e| args.only.is_empty() || args.only.iter().any(|w| w == e.name))
        .collect();

    eprintln!(
        "{} alpha(s) | {} market(s) from {} | batch {}",
        selected.len(),
        market_dirs.len(),
        data_dir,
        args.batch
    );

    for market_dir in market_dirs {
        let market_dir = market_dir.to_string_lossy();
        let files = engine::npz_files(&market_dir);
        eprintln!(
            "--- market {} | {} sessions ---",
            market_dir,
            files.len()
        );

        for e in &selected {
            eprintln!("=== {} (code {}) ===", e.name, e.code_hash);
            let t = Instant::now();
            (e.sweep)(
                &files,
                &market_dir,
                &data_root,
                out,
                args.batch,
                args.force,
            );
            eprintln!(
                "=== {} done in {:.1}s ===",
                e.name,
                t.elapsed().as_secs_f64()
            );
        }
    }
}
